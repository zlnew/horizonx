// Package config
package config

import (
	"fmt"
	"net"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/joho/godotenv"
)

type Config struct {
	AppEnv string

	LogLevel  string
	LogFormat string

	TimeZone       *time.Location
	Address        string
	AllowedOrigins []string
	DatabaseURL    string
	JWTSecret      string
	JWTExpiry      time.Duration

	AgentTargetAPIURL   string
	AgentTargetWsURL    string
	AgentServerAPIToken string
	AgentServerID       uuid.UUID
	AgentJobWorkerCount int

	// Retention TTLs for the ever-growing jobs/logs tables (parsed from
	// JOB_RETENTION_DAYS / LOG_RETENTION_DAYS, defaults 30 / 14).
	JobRetention time.Duration
	LogRetention time.Duration

	// P2-15: optional webhook notified on deployment events.
	// Discord-style: POSTed a JSON payload with a text content field.
	WebhookURL string

	// AutoMigrate runs pending DB migrations at server boot (Laravel-style).
	// Controlled by AUTO_MIGRATE, default true.
	AutoMigrate bool

	// AutoSeed creates the admin user at server boot when the users table is
	// empty (controlled by AUTO_SEED, default true). Credentials come from
	// ADMIN_EMAIL / ADMIN_PASSWORD (defaults admin@horizonx.local + random
	// generated by `install server` into the instance .env).
	AutoSeed   bool
	AdminEmail string
	AdminPass  string

	RedisAddress  string
	RedisUsername string
	RedisPassword string
	RedisDB       int

	// TrustProxy makes login rate limiting + session IP capture key on the
	// FIRST X-Forwarded-For entry instead of the tunnel's RemoteAddr. Set
	// true when the server sits behind a trusted proxy (Cloudflare tunnel /
	// tailscale serve — the default HorizonX topology). Leave false when the
	// box is directly exposed, where a spoofed XFF must not bypass the
	// limiter.
	TrustProxy bool
}

func Load() *Config {
	_ = godotenv.Load()

	appEnv := getEnv("APP_ENV", "local")

	// Logs
	logLevel := getEnv("LOG_LEVEL", "info")
	logFormat := getEnv("LOG_FORMAT", "text")

	// Server Time Zone
	timeZone, err := time.LoadLocation(getEnv("TIME_ZONE", "Local"))
	if err != nil {
		timeZone = time.Local
	}

	// Server HTTP Address
	addr := getEnv("HTTP_ADDR", ":3000")

	// Server Allowed Origins
	var origins []string
	rawOrigins := os.Getenv("ALLOWED_ORIGINS")
	if rawOrigins != "" {
		parts := strings.SplitSeq(rawOrigins, ",")
		for o := range parts {
			if trimmed := strings.TrimSpace(o); trimmed != "" {
				origins = append(origins, trimmed)
			}
		}
	}

	// Database URL
	databaseURL := getEnv("DATABASE_URL", "postgres://user:pass@localhost:5432/horizonx")

	// JWT Secret and Expiry
	jwtSecret := getEnv("JWT_SECRET", "")
	jwtExpiry := 24 * time.Hour
	if raw := os.Getenv("JWT_EXPIRY"); raw != "" {
		if duration, err := time.ParseDuration(raw); err == nil && duration > 0 {
			jwtExpiry = duration
		}
	}

	// AGENT Target URL
	agentTargetAPIURL := getEnv("HORIZONX_API_URL", "http://localhost:3000")
	agentTargetWsURL := getEnv("HORIZONX_WS_URL", "ws://localhost:3000/ws/agent")

	// AGENT Server Credentials
	agentServerAPIToken := getEnv("HORIZONX_SERVER_API_TOKEN", "")
	var agentServerID uuid.UUID
	if raw := os.Getenv("HORIZONX_SERVER_ID"); raw != "" {
		if serverID, err := uuid.Parse(raw); err == nil {
			agentServerID = serverID
		}
	}

	agentJobWorkerCount := 10
	if raw := os.Getenv("AGENT_JOB_WORKER_COUNT"); raw != "" {
		if count, err := strconv.Atoi(raw); err == nil {
			agentJobWorkerCount = count
		}
	}

	jobRetention := 30 * 24 * time.Hour
	if raw := os.Getenv("JOB_RETENTION_DAYS"); raw != "" {
		if days, err := strconv.Atoi(raw); err == nil && days > 0 {
			jobRetention = time.Duration(days) * 24 * time.Hour
		}
	}

	logRetention := 14 * 24 * time.Hour
	if raw := os.Getenv("LOG_RETENTION_DAYS"); raw != "" {
		if days, err := strconv.Atoi(raw); err == nil && days > 0 {
			logRetention = time.Duration(days) * 24 * time.Hour
		}
	}

	// P2-15: optional webhook (e.g. Discord) notified on deploy events.
	webhookURL := getEnv("WEBHOOK_URL", "")

	// Auto-migrate at boot unless explicitly disabled.
	autoMigrate := true
	if raw := strings.ToLower(os.Getenv("AUTO_MIGRATE")); raw != "" {
		autoMigrate = raw == "1" || raw == "true" || raw == "yes"
	}

	// Auto-seed the admin user at boot when the users table is empty.
	autoSeed := true
	if raw := strings.ToLower(os.Getenv("AUTO_SEED")); raw != "" {
		autoSeed = raw == "1" || raw == "true" || raw == "yes"
	}
	adminEmail := getEnv("ADMIN_EMAIL", "admin@horizonx.local")
	adminPass := getEnv("ADMIN_PASSWORD", "")

	// REDIS
	redisAddress := getEnv("REDIS_ADDR", "localhost:6379")
	redisUsername := getEnv("REDIS_USERNAME", "")
	redisPassword := getEnv("REDIS_PASS", "")
	redisDB := 0
	if raw := os.Getenv("REDIS_DB"); raw != "" {
		if value, err := strconv.Atoi(raw); err == nil {
			redisDB = value
		}
	}

	// TRUST_PROXY: default ON for the HorizonX topology (server binds
	// 127.0.0.1, exposed via Cloudflare tunnel / tailscale serve which set
	// X-Forwarded-For). Explicitly set TRUST_PROXY=false for direct exposure.
	trustProxy := true
	if raw := strings.ToLower(os.Getenv("TRUST_PROXY")); raw != "" {
		trustProxy = raw == "1" || raw == "true" || raw == "yes"
	}

	return &Config{
		AppEnv: appEnv,

		LogLevel:  logLevel,
		LogFormat: logFormat,

		TimeZone:       timeZone,
		Address:        addr,
		AllowedOrigins: origins,
		DatabaseURL:    databaseURL,
		JWTSecret:      jwtSecret,
		JWTExpiry:      jwtExpiry,

		AgentTargetAPIURL:   agentTargetAPIURL,
		AgentTargetWsURL:    agentTargetWsURL,
		AgentServerAPIToken: agentServerAPIToken,
		AgentServerID:       agentServerID,
		AgentJobWorkerCount: agentJobWorkerCount,

		JobRetention: jobRetention,
		LogRetention: logRetention,

		WebhookURL: webhookURL,

		AutoMigrate: autoMigrate,

		AutoSeed:   autoSeed,
		AdminEmail: adminEmail,
		AdminPass:  adminPass,

		RedisAddress:  redisAddress,
		RedisUsername: redisUsername,
		RedisPassword: redisPassword,
		RedisDB:       redisDB,
		TrustProxy:    trustProxy,
	}
}

func getEnv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// TrustProxyExposureWarning returns a warning when TRUST_PROXY is enabled while
// the API binds a non-loopback address, because any client that can reach the
// port can then forge X-Forwarded-For and defeat the login rate limiter and
// session-IP capture. It returns "" when there is nothing to report.
//
// This warns rather than refusing to boot, and that is deliberate. The
// documented topology binds all interfaces inside the container and publishes
// it on loopback from the host (install maps 127.0.0.1:${HORIZONX_PORT}:3000),
// so HTTP_ADDR is non-loopback in the supported install and a hard refusal
// would reject it. The process cannot tell from the inside whether the host
// publishes the port on loopback only, and the usual container heuristic is not
// reliable across runtimes. A check that silently disables itself on exactly
// the setups that need it is worse than a loud warning.
func (c *Config) TrustProxyExposureWarning() string {
	if c == nil || !c.TrustProxy {
		return ""
	}

	host := c.Address
	if h, _, err := net.SplitHostPort(c.Address); err == nil {
		host = h
	}

	if ip := net.ParseIP(host); ip != nil && ip.IsLoopback() {
		return ""
	}
	if strings.EqualFold(host, "localhost") {
		return ""
	}

	return fmt.Sprintf(
		"TRUST_PROXY is enabled but HTTP_ADDR=%q is not a loopback address: "+
			"any client able to reach this port can forge X-Forwarded-For and bypass "+
			"login rate limiting and session-IP capture. Bind the API to 127.0.0.1 and "+
			"front it with tailscale serve, or set TRUST_PROXY=false.",
		c.Address,
	)
}
